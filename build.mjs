import { mkdirSync, writeFileSync, cpSync, rmSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { layout, SITE } from './src/layout.mjs';
import * as P from './src/pages.mjs';
import { blogHub, blogPages } from './src/blog.mjs';
import { toolPages } from './src/tools.mjs';
import { offertePages } from './src/offerte.mjs';
import { LEADS, ROUTING, PREVIEW } from './src/leads.config.mjs';
const OUT = 'dist';
rmSync(OUT, { recursive: true, force: true });
const write = (p, s) => { mkdirSync(dirname(p), { recursive: true }); writeFileSync(p, s); };
export const pages = [P.home, P.quiz, P.subsidie, P.isde2027, P.glasisolatie, P.gidsHub, ...P.gidsPages, blogHub, ...blogPages, ...toolPages, ...offertePages, P.over, P.bronnen, P.privacy, P.disclaimer, P.notfound];
for (const p of pages) write(p.path.endsWith('.html') ? join(OUT, p.path) : join(OUT, p.path, 'index.html'), layout(p));
cpSync('src/assets/js', join(OUT, 'js'), { recursive: true });
cpSync('src/lib', join(OUT, 'js/lib'), { recursive: true });
// Offertepartners voor de browser (leeg = geen offerteknoppen). Alleen velden die de browser nodig heeft.
const pub = Object.fromEntries(Object.entries(LEADS).map(([id, x]) => [id, { naam: x.naam, type: x.type, url: x.url, origin: x.origin, privacy: x.privacy, max: x.max, prefill: x.prefill, subidParam: x.subidParam, klaar: x.klaar }]));
write(join(OUT, 'js/lib/leads.config.js'), `// Gegenereerd door build.mjs${PREVIEW ? ' (PREVIEW)' : ''}. Niet bewerken.\nexport const LEADS = ${JSON.stringify(pub)};\nexport const ROUTING = ${JSON.stringify(ROUTING)};\n`);
cpSync('src/assets/img', join(OUT, 'img'), { recursive: true });
cpSync('src/assets/og', join(OUT, 'og'), { recursive: true });
cpSync('src/assets/icons', OUT, { recursive: true });
cpSync('src/root', OUT, { recursive: true });
write(join(OUT, 'CNAME'), 'verduurzaammatch.nl\n');
write(join(OUT, '.nojekyll'), '');
write(join(OUT, 'robots.txt'), PREVIEW ? 'User-agent: *\nDisallow: /\n' : `User-agent: *\nAllow: /\n\nSitemap: ${SITE.domain}/sitemap.xml\n`);
write(join(OUT, 'sitemap.xml'), `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${pages.filter((p) => !p.noindex).map((p) => `<url><loc>${SITE.domain}${p.path}</loc><lastmod>${p.lastmod || SITE.updated}</lastmod></url>`).join('\n')}\n</urlset>\n`);
console.log(`Built ${pages.length} pages → ${OUT}/${PREVIEW ? ' (LEADS PREVIEW, niet deployen)' : ''}`);
